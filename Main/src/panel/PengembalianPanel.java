    private void konfirmasiPengembalianButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_konfirmasiPengembalianButtonActionPerformed
        if(JOptionPane.showConfirmDialog(null, "Yakin Ingin Konfirmasi Pengembalian [?]", "KONFIRMASI", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION){
            double subTotal = ps.pengembalianProduk(Integer.parseInt(idDetailTextField.getText()));
            if (subTotal < 0) {
                JOptionPane.showMessageDialog(null, "Pengembalian gagal diproses.", "PENGEMBALIAN GAGAL", JOptionPane.ERROR_MESSAGE);
                return;
            }
            JOptionPane.showMessageDialog(null, "Pengembalian berhasil, Sub total pengembalian: " +subTotal, "PENGEMBALIAN SUKSES", JOptionPane.INFORMATION_MESSAGE);
            if(tc.searchById(Integer.parseInt(idTransaksiTextField.getText())) == null){
                clearText();
                setButton(false);
                idTransaksiTextField.setText("");
                mapToTransaksiTable();
                mapToDetailTransaksiTableEmpty();
            }else{
                clearText();
                setButton(false);
                mapToTransaksiTable();
                mapToDetailTransaksiTable(Integer.parseInt(idTransaksiTextField.getText()));
            }
        }
    }//GEN-LAST:event_konfirmasiPengembalianButtonActionPerformed


