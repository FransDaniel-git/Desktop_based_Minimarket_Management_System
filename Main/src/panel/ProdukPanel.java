    private void searchProdukButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchProdukButtonActionPerformed
        try{
            if(isSelectedSearchById()){
                if(NumberUtils.isDigits(searchProdukTextField.getText())){
                    int id_produk = Integer.parseInt(searchProdukTextField.getText());
                    produkTable.setModel(pc.mapToProdukTableById(id_produk));
                }else{
                    throw new NumberException("Inputan Search Harus Berisi Angka [!]");
                }
            }else{
                produkTable.setModel(pc.mapToProdukTableByNama(searchProdukTextField.getText()));
            }
        }catch(NumberException ne){
            System.out.println("Input harus angka [!]");
            JOptionPane.showMessageDialog(null, "ID harus berupa angka saja [!]", "INPUT ERROR", JOptionPane.ERROR_MESSAGE);
        }catch(Exception e){
            System.out.println("Unexpected Error [!]");
            JOptionPane.showMessageDialog(null, "Unexpected Error [!]", "UNEXPECTED ERROR", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_searchProdukButtonActionPerformed

