    public void isInputKosong() throws EmptyException {
        if (idProdukTextField.getText().isBlank() ||
            namaProdukTextField.getText().isBlank() ||
            tipeProdukComboBox.getSelectedIndex() == -1 ||
            hargaProdukTextField.getText().isBlank() ||
            stokProdukTextField.getText().isBlank()) {
            throw new EmptyException("Input tidak boleh kosong [!]");
        }
    }

    public void isInputAngka() throws NumberException {
    String hargaProdukRegex = "[0-9]+([.]{1}[0-9]+)?";

    if (!hargaProdukTextField.getText().matches(hargaProdukRegex)) {
        throw new NumberException("Harga produk harus angka atau desimal [!]");
    }

    if (!NumberUtils.isDigits(stokProdukTextField.getText())) {
        throw new NumberException("Stok produk harus angka [!]");
    }
}
    

