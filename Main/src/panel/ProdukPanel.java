    private void confirmProdukButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_confirmProdukButtonActionPerformed
        if(action==null){
            return;
        }
        
        try{
            isInputKosong();
            isInputAngka();

            String nama = namaProdukTextField.getText();
            String tipe = tipeProdukComboBox.getItemAt(tipeProdukComboBox.getSelectedIndex());
            double harga = Double.parseDouble(hargaProdukTextField.getText());
            int stok = Integer.parseInt(stokProdukTextField.getText());

            if(JOptionPane.showConfirmDialog(null, "Yakin ingin melakukan " + action + "?", "Konfirmasi", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION){
                if(action.equals("Create")){
                    Produk p = new Produk(
                    nama, 
                    tipe, 
                    harga, 
                    stok);
                    pc.create(p);
                }else{
                    Produk p = new Produk(
                    nama, 
                    tipe, 
                    harga, 
                    stok);
                    pc.update(p, Integer.parseInt(idProdukTextField.getText()));
                }
            }
        }catch(EmptyException ee){
            System.out.println(ee.toString());
            JOptionPane.showMessageDialog(null, ee.getMessage(), "INPUT KOSONG", JOptionPane.ERROR_MESSAGE);
            return;
        }catch(NumberException ne){
            System.out.println(ne.toString());
            JOptionPane.showMessageDialog(null, ne.getMessage(), "INPUT HARUS ANGKA", JOptionPane.ERROR_MESSAGE);
            return;
        }catch(Exception e){
            System.out.println("Unexpected Error [!]");
            JOptionPane.showMessageDialog(null, "Unexpected Error [!]", "UNEXPECTED ERROR", JOptionPane.ERROR_MESSAGE);
        }
        
        clearText();
        setComponent(false);
        setUpdateDelete(false);
        action = null;
        showTable();
        cancelProdukButton.setEnabled(false);
        confirmProdukButton.setEnabled(false);
        createProdukButton.setEnabled(true);
    }//GEN-LAST:event_confirmProdukButtonActionPerformed

