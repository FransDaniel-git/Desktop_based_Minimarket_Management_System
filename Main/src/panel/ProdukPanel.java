    private void produkTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_produkTableMouseClicked
        setUpdateDelete(true);
        setComponent(false);
        clearText();
        
        int clickedRow = produkTable.getSelectedRow();
        TableModel t = produkTable.getModel();
        
        idProdukTextField.setText(t.getValueAt(clickedRow, 0).toString());
        namaProdukTextField.setText(t.getValueAt(clickedRow, 1).toString());
        String tipe = t.getValueAt(clickedRow, 2).toString();
        tipeProdukComboBox.setSelectedItem(tipe);
        hargaProdukTextField.setText(t.getValueAt(clickedRow, 3).toString());
        stokProdukTextField.setText(t.getValueAt(clickedRow, 4).toString());
        createProdukButton.setEnabled(false);
        cancelProdukButton.setEnabled(true);
    }//GEN-LAST:event_produkTableMouseClicked

