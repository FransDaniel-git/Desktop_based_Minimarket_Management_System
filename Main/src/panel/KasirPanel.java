        if(opsi == JOptionPane.NO_OPTION || opsi == JOptionPane.CLOSED_OPTION){
            return;
        }

        kc.delete(Integer.parseInt(idKasirTextField.getText()));
        setComponent(false);
        setUpdateDelete(false);
        clearText();
        showTable();
        cancelKasirButton.setEnabled(false);
