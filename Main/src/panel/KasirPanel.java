    private void confirmKasirButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_confirmKasirButtonActionPerformed
        if(action==null){
            return;
        }

        try{
            isInputKosong();
            String nama = namaKasirTextField.getText();
            if(JOptionPane.showConfirmDialog(null, "Yakin ingin melakukan " + action + "?", "Konfirmasi", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION){
                if(action.equals("Create")){
                    Kasir kasir = new Kasir(nama);
                    kc.create(kasir);
                }else{
                    Kasir kasir = new Kasir(nama);
                    kc.update(kasir, Integer.parseInt(idKasirTextField.getText()));
                }
            }
        }catch(EmptyException ee){
            System.out.println(ee.toString());
            JOptionPane.showMessageDialog(null, ee.getMessage(), "INPUT KOSONG", JOptionPane.ERROR_MESSAGE);
            return;
        }catch(Exception e){
            System.out.println("Unexpected Error [!]");
            JOptionPane.showMessageDialog(null, "Unexpected Error [!]", "UNEXPECTED ERROR", JOptionPane.ERROR_MESSAGE);
        }

        clearText();
        setComponent(false);
        setUpdateDelete(false);
        action = null;
        showTable();
        cancelKasirButton.setEnabled(false);
        confirmKasirButton.setEnabled(false);
        createKasirButton.setEnabled(true);
    }//GEN-LAST:event_confirmKasirButtonActionPerformed

