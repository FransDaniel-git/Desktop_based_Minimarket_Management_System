    public void isInputJumlahEmpty() throws EmptyException{
        if(jumlahDibeliTextField.getText().isBlank()){
            throw new EmptyException("Input tidak boleh kosong [!]");
        }
    }
    
    public void isInputJumlahNumber() throws NumberException{
        if(!(NumberUtils.isDigits(jumlahDibeliTextField.getText()))){
            throw new NumberException("Input hanya boleh angka [!]");
        }
    }
    
    public void isInputJumlahHigherThanStok() throws InvalidException{
        if((Integer.parseInt(jumlahDibeliTextField.getText())) > (selectedProduk.getStok())){
            throw new InvalidException("Input jumlah tidak boleh melebihi stok [!]");
        }
    }
    
    public void isInputKasirOrNamaPembeliEmpty() throws EmptyException{
        if(namaPembeliTextField.getText().isBlank() || kasirComboBox.getSelectedIndex()==-1){
            throw new EmptyException("Input tidak boleh kosong [!]");
        }
    }
    
    private int ProdukAlreadyChoosen(Produk produk) {
        for(ProdukDibeli pd: listProdukDibeli){
            if(produk.isEqual(pd.getProduk())){
                return listProdukDibeli.indexOf(pd);
            }
        }
        return -1;
    }

