    private void kosongkanKeranjangButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_kosongkanKeranjangButtonActionPerformed
        if(JOptionPane.showConfirmDialog(null, "Yakin ingin mengosongkan keranjang [?]", "KONFIRMASI", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION){
            List<Produk> listTempProduk = new ArrayList<>();
            for (ProdukDibeli pd : listProdukDibeli) {
                Produk p = pd.getProduk();
                p.setStok(p.getStok() + pd.getJumlah());
                listTempProduk.add(p);
            }
            pc.batchUpdate(listTempProduk);
            
            konfirmasiTransaksiButton.setEnabled(false);
            kosongkanKeranjangButton.setEnabled(false);
            namaPembeliTextField.setText("");
            kasirComboBox.setSelectedIndex(-1);
            namaPembeliTextField.setEnabled(false);
            kasirComboBox.setEnabled(false);
            listProdukDibeli.clear();
            clearText();
            setComponent(false);
            selectedProduk = null;
            refreshTable();
        }
    }//GEN-LAST:event_kosongkanKeranjangButtonActionPerformed


