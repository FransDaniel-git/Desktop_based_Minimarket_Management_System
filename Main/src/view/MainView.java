    private void produkPanelMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_produkPanelMouseClicked
        if(selectedIndex == 1){
            return;
        }
        
        if(selectedIndex == 3){
            if(!(tempPembelianPanel.getListProdukDibeli().isEmpty())){
                if(JOptionPane.showConfirmDialog(null, "Mengganti ke panel lain berarti mengosongkan keranjang saat ini, Konfirmasi?", "KONFIRMASI", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION){
                    tempPembelianPanel.resetKeranjang();
                }else{
                    return;
                }
            }
        }
        
        recolorDefaultSwitchPanel();
        produkPanel.setBackground(new Color(0, 204, 255));
        setForm(new ProdukPanel());
        selectedIndex = 1;
    }//GEN-LAST:event_produkPanelMouseClicked

